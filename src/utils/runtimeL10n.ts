type TranslationKey = keyof typeof translations.en | keyof typeof uiTranslations;

function isUiTranslation(key: TranslationKey): key is keyof typeof uiTranslations {
    return key in uiTranslations;
}

function getRuntimeLanguage(): RuntimeLanguage {
    const language = vscode.env.language.toLowerCase();
    if (language.startsWith("es")) {
        return "es";
    }
    if (language.startsWith("de")) {
        return "de";
    }
    return "en";
}

export function rt(key: TranslationKey, ...args: Array<string | number>): string {
    const lang = getRuntimeLanguage();
    const template = isUiTranslation(key)
        ? uiTranslations[key][lang]
        : lang === "de" ? germanTranslations[key] : translations[lang][key];
    return template.replace(/\{(\d+)\}/g, (_, index) => String(args[Number(index)] ?? ""));
}
